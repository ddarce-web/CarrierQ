"""Command line: the tool you use for the manual 'free audit' phase.

  parcelaudit demo out/
  parcelaudit audit -r ratecard.yaml -i invoice.csv [-i more.pdf] [-s shipments.csv] -o out/
  parcelaudit draft-ratecard contract.pdf -o ratecard.draft.yaml
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from .audit import run_audit
from .ingest.common import read_csv
from .ingest.invoices import INVOICE_SYNONYMS, MappingError, parse_invoice_csv
from .ingest.shipments import SHIPMENT_SYNONYMS, parse_shipments_csv
from .ratecard import load_ratecard
from .report import dispute_email, findings_csv, render_html


def _load_mapping(path: str | None, section: str) -> dict | None:
    if not path:
        return None
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    return data.get(section)


def _parse_invoice(path: Path, rc, mapping, use_llm: bool):
    data = path.read_bytes()
    if path.suffix.lower() == ".pdf":
        if not use_llm:
            raise SystemExit(f"{path}: PDF invoices need --use-llm (or ask for the CSV export).")
        from .llm import extract_pdf_invoice
        return extract_pdf_invoice(data), []
    try:
        return parse_invoice_csv(data, rc, mapping)
    except MappingError as e:
        if not use_llm:
            raise SystemExit(f"{path}: {e}\nProvide --mapping or use --use-llm to let Claude map columns.")
        from .llm import suggest_mapping
        headers, rows = read_csv(data)
        m = suggest_mapping(headers, rows, INVOICE_SYNONYMS)
        print(f"  Claude suggested invoice mapping for {path.name}: {json.dumps(m, ensure_ascii=False)}")
        return parse_invoice_csv(data, rc, m)


def cmd_audit(args) -> int:
    rc = load_ratecard(args.ratecard)
    lines, warnings = [], []
    for p in args.invoice:
        ls, ws = _parse_invoice(Path(p), rc, _load_mapping(args.mapping, "invoice"), args.use_llm)
        lines += ls
        warnings += [f"{Path(p).name}: {w}" for w in ws]
    shipments = None
    if args.shipments:
        data = Path(args.shipments).read_bytes()
        mapping = _load_mapping(args.mapping, "shipments")
        try:
            shipments = parse_shipments_csv(data, mapping)
        except MappingError:
            if not args.use_llm:
                raise
            from .llm import suggest_mapping
            headers, rows = read_csv(data)
            shipments = parse_shipments_csv(data, suggest_mapping(headers, rows, SHIPMENT_SYNONYMS))

    result = run_audit(lines, rc, shipments, warnings)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.html").write_text(render_html(result, args.customer, args.period), encoding="utf-8")
    (out / "findings.csv").write_text(findings_csv(result), encoding="utf-8-sig")
    (out / "dispute_email.txt").write_text(dispute_email(result, args.customer or "[Firma]"), encoding="utf-8")
    (out / "result.json").write_text(result.model_dump_json(indent=2), encoding="utf-8")

    print(f"Audited {result.lines_audited} parcels, €{result.total_billed:,.2f} billed.")
    for key, row in result.by_rule().items():
        print(f"  {row['title']:<45} {row['count']:>4}  €{row['amount']:>9,.2f}")
    print(f"Overbilled (high+medium): €{result.recoverable():,.2f} ({result.overbilled_pct():.1f}% of spend)")
    if result.claims_value():
        print(f"Lost/damaged claims to file: €{result.claims_value():,.2f}")
    for w in result.warnings:
        print(f"  ! {w}")
    print(f"Report: {out / 'report.html'}")
    return 0


def cmd_demo(args) -> int:
    from .sample import generate
    paths = generate(args.out)
    print(f"Sample data written to {args.out}. Injected errors: {paths['_expected']}")
    ns = argparse.Namespace(ratecard=paths["ratecard"], invoice=[paths["invoice"]], shipments=paths["shipments"],
                            mapping=None, use_llm=False, out=args.out, customer="Demo Shop GmbH",
                            period="September 2026")
    return cmd_audit(ns)


def cmd_draft_ratecard(args) -> int:
    from .llm import draft_ratecard
    rc, uncertain = draft_ratecard(Path(args.contract).read_bytes())
    header = "# DRAFT generated by Claude – review every price against the contract before use.\n"
    if uncertain:
        header += "# Open questions:\n" + "".join(f"#  - {u}\n" for u in uncertain)
    Path(args.out).write_text(header + yaml.safe_dump(rc, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"Draft written to {args.out}" + (f" ({len(uncertain)} open questions)" if uncertain else ""))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="parcelaudit", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    a = sub.add_parser("audit", help="audit invoices against a rate card")
    a.add_argument("-r", "--ratecard", required=True)
    a.add_argument("-i", "--invoice", action="append", required=True, help="CSV or PDF; repeatable")
    a.add_argument("-s", "--shipments", help="shop label/order export CSV")
    a.add_argument("-m", "--mapping", help="YAML with 'invoice:' and/or 'shipments:' column mappings")
    a.add_argument("-o", "--out", default="audit_out")
    a.add_argument("--customer", default="")
    a.add_argument("--period", default="")
    a.add_argument("--use-llm", action="store_true", help="allow Claude for PDFs / unknown column layouts")
    a.set_defaults(func=cmd_audit)

    d = sub.add_parser("demo", help="generate sample data and audit it")
    d.add_argument("out", nargs="?", default="demo_out")
    d.set_defaults(func=cmd_demo)

    r = sub.add_parser("draft-ratecard", help="draft a rate card YAML from a contract PDF (Claude)")
    r.add_argument("contract")
    r.add_argument("-o", "--out", default="ratecard.draft.yaml")
    r.set_defaults(func=cmd_draft_ratecard)

    args = ap.parse_args(argv)
    try:
        return args.func(args)
    except Exception as e:  # surface LLM/config errors cleanly
        from .llm import LLMError
        if isinstance(e, (LLMError, MappingError)):
            print(f"Error: {e}", file=sys.stderr)
            return 1
        raise


if __name__ == "__main__":
    sys.exit(main())
